# POST /ingest
# ══════════════════════════════════════════════════════════════════════════════

@router.post(
    "/ingest",
    response_model=IngestResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Ingest a PDF document",
    description=(
        "Upload a multimodal PDF. The pipeline extracts:\n"
        "- **Text** chunks (PyMuPDF)\n"
        "- **Table** chunks converted to Markdown (pdfplumber)\n"
        "- **Image** chunks summarised by Claude Vision VLM, then embedded\n\n"
        "All chunks are embedded with `sentence-transformers/all-MiniLM-L6-v2` "
        "and stored in ChromaDB. Returns ingestion summary with chunk counts by type "
        "and total processing time."
    ),
    tags=["Ingestion"],
    responses={
        400: {"model": ErrorResponse, "description": "Invalid file type"},
        413: {"model": ErrorResponse, "description": "File too large (> 100 MB)"},
        500: {"model": ErrorResponse, "description": "Ingestion failed"},
    },
)
async def ingest_document(
    file: UploadFile = File(
        ...,
        description="PDF file to ingest. Must be a valid PDF document.",
    ),
    collection: str = Form(
        "diagnostic_rag",
        description="ChromaDB collection name. Created if it does not exist.",
    ),
    use_vision: bool = Form(
        True,
        description=(
            "Whether to summarise images with Claude Vision. "
            "Set to false to skip image processing (faster but no image retrieval)."
        ),
    ),
) -> IngestResponse:
    # ── Validate ──────────────────────────────────────────────────────────────
    if not file.filename or not file.filename.lower().endswith(".pdf"):
        raise HTTPException(
            status_code=400,
            detail="Only PDF files are accepted. Please upload a .pdf file.",
        )

    content = await file.read()

    if len(content) == 0:
        raise HTTPException(status_code=400, detail="Uploaded file is empty.")

    max_bytes = 100 * 1024 * 1024  # 100 MB
    if len(content) > max_bytes:
        raise HTTPException(
            status_code=413,
            detail=f"File size ({len(content) // (1024*1024)} MB) exceeds 100 MB limit.",
        )

    # ── Save to temp file ─────────────────────────────────────────────────────
    tmp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            delete=False, suffix=".pdf", prefix="rag_upload_"
        ) as tmp:
            tmp.write(content)
            tmp_path = Path(tmp.name)

        # ── Run pipeline ──────────────────────────────────────────────────────
        from src.ingestion.pipeline import IngestionPipeline

        pipeline = IngestionPipeline(collection=collection, use_vision=use_vision)
        result = await pipeline.run_async(tmp_path)

        # Determine status
        ingest_status = "success"
        if result.errors:
            ingest_status = "partial" if result.chunk_counts["total"] > 0 else "error"

        return IngestResponse(
            status=ingest_status,
            filename=file.filename,
            collection=result.collection,
            total_pages=result.total_pages,
            chunk_counts=ChunkCounts(**result.chunk_counts),
            processing_time_s=result.processing_time_s,
            warnings=result.errors[:10],  # cap at 10 warnings
            message=(
                f"Successfully indexed {result.chunk_counts['total']} chunks "
                f"({result.chunk_counts['text']} text, "
                f"{result.chunk_counts['table']} table, "
                f"{result.chunk_counts['image']} image) "
                f"from {result.total_pages} pages."
            ),
        )

    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Ingestion failed: {type(exc).__name__}: {exc}",
        )
    finally:
        if tmp_path and tmp_path.exists():
            tmp_path.unlink(missing_ok=True)


