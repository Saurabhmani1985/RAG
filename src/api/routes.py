# POST /query
# ══════════════════════════════════════════════════════════════════════════════

@router.post(
    "/query",
    response_model=QueryResponse,
    summary="Query the RAG system",
    description=(
        "Submit a natural language question. The system:\n"
        "1. Embeds the question with the same model used during ingestion\n"
        "2. Retrieves the top-k most relevant chunks from ChromaDB "
        "(text, table, and image-summary chunks)\n"
        "3. Assembles a structured context using the custom RAG prompt template\n"
        "4. Generates a grounded answer via Claude\n"
        "5. Returns the answer with full source references "
        "(filename, page, chunk type, relevance score, excerpt)\n\n"
        "Optionally filter retrieval to a specific `chunk_type_filter` "
        "(`text`, `table`, or `image`) to demonstrate modality-specific retrieval."
    ),
    tags=["Query"],
    responses={
        404: {"model": ErrorResponse, "description": "No documents indexed in collection"},
        500: {"model": ErrorResponse, "description": "Retrieval or generation failed"},
    },
)
async def query(request: QueryRequest) -> QueryResponse:
    from src.retrieval.retriever import get_retriever
    from src.retrieval.vector_store import get_vector_store

    # Check collection has data
    store = get_vector_store()
    count = store.collection_count(request.collection)
    if count == 0:
        raise HTTPException(
            status_code=404,
            detail=(
                f"Collection '{request.collection}' is empty or does not exist. "
                "Please ingest a document first via POST /ingest."
            ),
        )

    try:
        retriever = get_retriever()
        result = retriever.query(
            question=request.question,
            top_k=request.top_k,
            collection=request.collection,
            chunk_type_filter=request.chunk_type_filter,
        )
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Query failed: {type(exc).__name__}: {exc}",
        )

    sources = [
        SourceReference(
            filename=s.filename,
            page=s.page,
            chunk_type=s.chunk_type,
            score=s.score,
            excerpt=s.excerpt,
        )
        for s in result.sources
    ]

    rs = result.retrieval_stats
    return QueryResponse(
        question=result.question,
        answer=result.answer,
        sources=sources,
        retrieval_stats=RetrievalStats(
            total_retrieved=rs["total_retrieved"],
            by_type=rs["by_type"],
            collection=rs["collection"],
            top_k_requested=rs["top_k_requested"],
            llm_input_tokens=rs["llm_input_tokens"],
            llm_output_tokens=rs["llm_output_tokens"],
            llm_latency_ms=rs["llm_latency_ms"],
        ),
        latency_ms=result.latency_ms,
        model=result.model,
    )


