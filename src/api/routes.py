# DELETE /delete
# ══════════════════════════════════════════════════════════════════════════════

@router.delete(
    "/delete",
    response_model=DeleteResponse,
    summary="Delete a document from the index",
    description=(
        "Remove all chunks belonging to a specific document filename from the "
        "vector store. The document can be re-ingested afterwards."
    ),
    tags=["Management"],
)
def delete_document(request: DeleteRequest) -> DeleteResponse:
    from src.retrieval.vector_store import get_vector_store

    store = get_vector_store()
    removed = store.delete_document(
        source=request.filename,
        collection=request.collection,
    )

    if removed == 0:
        return DeleteResponse(
            status="not_found",
            filename=request.filename,
            chunks_removed=0,
            message=f"No chunks found for '{request.filename}' in '{request.collection}'.",
        )

    return DeleteResponse(
        status="deleted",
        filename=request.filename,
        chunks_removed=removed,
        message=f"Removed {removed} chunks for '{request.filename}'.",
    )
