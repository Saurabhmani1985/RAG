# ══════════════════════════════════════════════════════════════════════════════
# GET /health
# ══════════════════════════════════════════════════════════════════════════════

@router.get(
    "/health",
    response_model=HealthResponse,
    summary="System health check",
    description=(
        "Returns model readiness, vector store stats (number of indexed documents, "
        "total chunk count, approximate index size), and server uptime."
    ),
    tags=["System"],
)
def health_check() -> HealthResponse:
    from src.config import get_settings
    from src.retrieval.vector_store import get_vector_store

    cfg = get_settings()
    components: dict[str, ComponentStatus] = {}

    # Check vector store
    try:
        store = get_vector_store()
        stats = store.get_stats()
        total_chunks = stats["total_chunks"]
        docs = store.list_indexed_documents()
        indexed_docs = len(docs)
        components["vector_store"] = ComponentStatus(
            status="ok",
            detail=f"ChromaDB — {total_chunks} chunks in '{cfg.default_collection}'",
        )
    except Exception as exc:
        total_chunks = 0
        indexed_docs = 0
        components["vector_store"] = ComponentStatus(
            status="unavailable", detail=str(exc)
        )

    # Check embedding model (lazy-load attempt)
    try:
        from src.ingestion.embedder import get_embedder
        emb = get_embedder()
        components["embedding_model"] = ComponentStatus(
            status="ok", detail=f"{cfg.embedding_model} (dim={emb.dim})"
        )
    except Exception as exc:
        components["embedding_model"] = ComponentStatus(
            status="unavailable", detail=str(exc)
        )

    # Check LLM (API key present)
    api_key_ok = bool(cfg.anthropic_api_key and cfg.anthropic_api_key.startswith("sk-"))
    components["llm"] = ComponentStatus(
        status="ok" if api_key_ok else "unavailable",
        detail=cfg.llm_model if api_key_ok else "ANTHROPIC_API_KEY not set",
    )

    # Check vision model
    components["vision_model"] = ComponentStatus(
        status="ok" if api_key_ok else "unavailable",
        detail=cfg.vision_model if api_key_ok else "ANTHROPIC_API_KEY not set",
    )

    # Estimate index size from ChromaDB persist dir
    try:
        chroma_dir = cfg.chroma_persist_dir
        size_bytes = sum(
            f.stat().st_size
            for f in chroma_dir.rglob("*")
            if f.is_file()
        )
        index_size_mb = round(size_bytes / (1024 * 1024), 2)
    except Exception:
        index_size_mb = 0.0

    overall = (
        "ok"
        if all(c.status == "ok" for c in components.values())
        else "degraded"
    )

    return HealthResponse(
        status=overall,
        version="1.0.0",
        uptime_seconds=round(time.time() - _START_TIME, 1),
        indexed_documents=indexed_docs,
        total_chunks=total_chunks,
        index_size_mb=index_size_mb,
        components=components,
    )


