# GET /documents
# ══════════════════════════════════════════════════════════════════════════════

@router.get(
    "/documents",
    response_model=DocumentsResponse,
    summary="List all indexed documents",
    description=(
        "Returns a list of all documents currently indexed in the vector store, "
        "with per-document chunk counts broken down by type (text, table, image)."
    ),
    tags=["Management"],
)
def list_documents(
    collection: str = "diagnostic_rag",
) -> DocumentsResponse:
    from src.retrieval.vector_store import get_vector_store

    store = get_vector_store()
    docs = store.list_indexed_documents(collection)

    return DocumentsResponse(
        collection=collection,
        document_count=len(docs),
        documents=[
            DocumentInfo(
                filename=d["filename"],
                chunks=d["chunks"],
                total_chunks=d["total_chunks"],
            )
            for d in docs
        ],
    )


